const I18N_STATE = { lang: "en" };

function i18nSetLang(lang) {
  I18N_STATE.lang = I18N[lang] ? lang : "en";
  localStorage.setItem("derail:lang", I18N_STATE.lang);
}

function i18nGetLang() {
  return I18N_STATE.lang;
}

function t(key, params) {
  const dict = I18N[I18N_STATE.lang] || I18N.en;
  let str = key.split(".").reduce((o, k) => (o ? o[k] : undefined), dict);
  if (str === undefined) str = key.split(".").reduce((o, k) => (o ? o[k] : undefined), I18N.en);
  if (str === undefined) return key;
  if (Array.isArray(str)) return str;
  if (params) {
    Object.keys(params).forEach((p) => {
      str = str.replace(new RegExp(`\\{${p}\\}`, "g"), params[p]);
    });
  }
  return str;
}

function toastText(code, params) {
  return t(`toasts.${code}`, params);
}
